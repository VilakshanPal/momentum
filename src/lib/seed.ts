type ItemSeed = {
  title: string;
  detail?: string | null;
  owner?: string | null;
  due_on?: string | null;
  status: string;
  blocker?: string | null;
  evidence?: string | null;
  supersedes_id?: string | null;
  position: number;
};

export async function seed() {
  const c = await pool.connect();
  try {
    await c.query("begin");
    await c.query("truncate items, meetings, projects, people, clients cascade");
    await seedDemo(c);
    await seedExtra(c);

    await c.query("commit");
    return DEMO_PROJECT_ID;
  } catch (e) {
    await c.query("rollback");
    throw e;
  } finally {
    c.release();
  }
}

